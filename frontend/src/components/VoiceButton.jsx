import React, { useState, useRef, useEffect } from 'react';
import { Volume2, VolumeX, Loader2 } from 'lucide-react';
import { useLanguage } from '../context/LanguageContext';
import { languageApi } from '../services/api';

const LOCALE_MAP = {
  en: 'en-IN',
  ta: 'ta-IN',
  te: 'te-IN',
  hi: 'hi-IN',
  ml: 'ml-IN',
  kn: 'kn-IN',
  bn: 'bn-IN',
  mr: 'mr-IN'
};

const LANG_NAMES = {
  en: 'English',
  ta: 'தமிழ்',
  te: 'తెలుగు',
  hi: 'हिन्दी',
  ml: 'മലയാളം',
  kn: 'ಕನ್ನಡ',
  bn: 'বাংলা',
  mr: 'मराठी'
};

export default function VoiceButton({ text, className = '', label = null }) {
  const { currentLang, t } = useLanguage();
  const [isSpeaking, setIsSpeaking] = useState(false);
  const [loading, setLoading] = useState(false);
  const audioRef = useRef(null);

  // Clean up any playing audio when component unmounts
  useEffect(() => {
    return () => {
      if (audioRef.current) {
        audioRef.current.pause();
        audioRef.current = null;
      }
      if ('speechSynthesis' in window) {
        window.speechSynthesis.cancel();
      }
    };
  }, []);

  const stopPlayback = () => {
    if (audioRef.current) {
      audioRef.current.pause();
      audioRef.current.currentTime = 0;
      audioRef.current = null;
    }
    if ('speechSynthesis' in window) {
      window.speechSynthesis.cancel();
    }
    setIsSpeaking(false);
    setLoading(false);
  };

  const playBrowserSpeechFallback = (speechText, targetLocale) => {
    if (!('speechSynthesis' in window)) {
      setIsSpeaking(false);
      setLoading(false);
      return;
    }

    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(speechText);
    utterance.lang = targetLocale;
    utterance.rate = 0.92;
    utterance.pitch = 1.0;

    const voices = window.speechSynthesis.getVoices();
    const matchingVoice = voices.find(
      (v) => v.lang === targetLocale || v.lang.startsWith(currentLang)
    );
    if (matchingVoice) {
      utterance.voice = matchingVoice;
    }

    utterance.onstart = () => {
      setIsSpeaking(true);
      setLoading(false);
    };
    utterance.onend = () => {
      setIsSpeaking(false);
    };
    utterance.onerror = () => {
      setIsSpeaking(false);
      setLoading(false);
    };

    window.speechSynthesis.speak(utterance);
  };

  const handleSpeak = async (e) => {
    e.stopPropagation();

    // If currently speaking, stop immediately
    if (isSpeaking || loading) {
      stopPlayback();
      return;
    }

    if (!text) return;

    setLoading(true);

    try {
      // Fetch speech payload with authentic native regional audio from backend
      const res = await languageApi.speech(text, currentLang);
      const data = res.data || {};

      // 1. Prioritize authentic regional MP3 audio generated by backend
      if (data.has_audio && data.audio_base64) {
        if (audioRef.current) {
          audioRef.current.pause();
          audioRef.current = null;
        }

        const audio = new Audio(`data:audio/mp3;base64,${data.audio_base64}`);
        audioRef.current = audio;

        audio.onplay = () => {
          setIsSpeaking(true);
          setLoading(false);
        };

        audio.onended = () => {
          setIsSpeaking(false);
          audioRef.current = null;
        };

        audio.onerror = (err) => {
          console.warn('Backend audio playback error, falling back to browser TTS:', err);
          playBrowserSpeechFallback(data.text || text, data.voice_locale || LOCALE_MAP[currentLang] || 'en-IN');
        };

        try {
          await audio.play();
        } catch (playErr) {
          console.warn('Autoplay blocked or audio failed, trying browser TTS:', playErr);
          playBrowserSpeechFallback(data.text || text, data.voice_locale || LOCALE_MAP[currentLang] || 'en-IN');
        }
      } else {
        // 2. Fallback to browser SpeechSynthesis with translated regional text
        const speechText = data.text || text;
        const targetLocale = data.voice_locale || LOCALE_MAP[currentLang] || 'en-IN';
        playBrowserSpeechFallback(speechText, targetLocale);
      }
    } catch (error) {
      console.warn('Speech API request error, falling back to browser speech:', error);
      playBrowserSpeechFallback(text, LOCALE_MAP[currentLang] || 'en-IN');
    }
  };

  const langName = LANG_NAMES[currentLang] || currentLang.toUpperCase();
  const buttonLabel = label || (isSpeaking ? t('analysis.speaking') : `${t('analysis.listen')} (${langName})`);

  return (
    <button
      type="button"
      onClick={handleSpeak}
      className={`inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition border shadow-xs cursor-pointer select-none ${
        isSpeaking
          ? 'bg-teal-600 hover:bg-teal-700 text-white border-teal-700 ring-2 ring-teal-400/50 animate-pulse'
          : loading
          ? 'bg-slate-100 text-slate-500 border-slate-300'
          : 'bg-white hover:bg-teal-50 text-slate-700 hover:text-teal-800 border-slate-200 hover:border-teal-300'
      } ${className}`}
      title={isSpeaking ? 'Stop voice playback' : `Listen explanation in ${langName}`}
      aria-label="Voice assistance in regional language"
    >
      {loading ? (
        <Loader2 className="w-3.5 h-3.5 animate-spin text-teal-600" />
      ) : isSpeaking ? (
        <VolumeX className="w-3.5 h-3.5 text-white" />
      ) : (
        <Volume2 className="w-3.5 h-3.5 text-teal-600" />
      )}
      <span className="truncate">{buttonLabel}</span>
    </button>
  );
}
